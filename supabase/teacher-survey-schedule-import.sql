-- Добавляем только отсутствующих преподавателей.
insert into public.survey_teachers(full_name, active)
select distinct i.teacher_name, true
from public._teacher_schedule_import i
where not exists (
  select 1 from public.survey_teachers t
  where lower(trim(t.full_name)) = lower(trim(i.teacher_name))
);

-- Заново формируем привязки только для групп из данного расписания.
delete from public.survey_group_teachers gt
using public.survey_groups g
where gt.group_id = g.id
  and g.name in (select distinct group_name from public._teacher_schedule_import);

insert into public.survey_group_teachers(group_id, teacher_id, subject, sort_order, active)
select g.id, t.id, i.subject,
       row_number() over (partition by g.id order by i.sort_order)::integer,
       true
from public._teacher_schedule_import i
join public.survey_groups g on g.name = i.group_name
join lateral (
  select st.id
  from public.survey_teachers st
  where lower(trim(st.full_name)) = lower(trim(i.teacher_name))
  order by st.created_at, st.id
  limit 1
) t on true;

